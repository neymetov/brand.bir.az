/**
 * Куда вернуть пользователя после входа.
 *
 * `from` приходит из адресной строки, то есть его может подставить кто угодно
 * — например, прислать ссылку `/login?from=https://evil.example`. Без этой
 * проверки форма логина уводила бы на чужой домен сразу после ввода пароля:
 * классический open redirect, вдвойне неприятный на странице, где только что
 * вводили пароль.
 *
 * Пропускаем только внутренний абсолютный путь. `//host` и `/\host` браузер
 * трактует как protocol-relative URL — это тот же уход на чужой домен, поэтому
 * одной проверки на ведущий `/` мало.
 *
 * Лежит отдельным модулем, а не внутри страницы логина: правило проверяется
 * тестом, а страница — клиентский компонент, из теста её не вызвать.
 */
export function safeReturnPath(from: string | null): string | null {
  if (!from) return null;
  if (!from.startsWith('/')) return null;
  if (from.startsWith('//') || from.startsWith('/\\')) return null;
  return from;
}
