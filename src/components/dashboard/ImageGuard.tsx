'use client';

import { useEffect } from 'react';

// Убирает контекстное меню на изображениях: без него нет пункта «Сохранить
// изображение как…» (требование пользователя, 2026-08-10).
//
// ЧЕСТНО О ГРАНИЦАХ. Это затруднение, а не защита. Чтобы браузер показал
// картинку, её байты обязаны в него попасть — значит она уже лежит в кэше, в
// панели «Сеть» инструментов разработчика и попадает на любой скриншот. Ни
// CSS, ни JavaScript этого не отменяют, и «закрыть inspect» нельзя в принципе:
// инструменты разработчика — часть браузера, а не страницы. Всё, что делают
// популярные приёмы вроде отключения F12 — ломают жизнь честному
// пользователю, не мешая тому, кто действительно захочет забрать файл.
// Подробнее — docs/OPEN_QUESTIONS.md №119.
//
// Слушатель один на документ, а не обработчик на каждой картинке: изображения
// приходят из блоков CMS, и обвешивать их поштучно значит забыть про новый
// блок. Слушатель ставится только в читательской оболочке — в редакторе
// контекстное меню админу нужно.
export function ImageGuard() {
  useEffect(() => {
    const onContextMenu = (event: MouseEvent) => {
      if (event.target instanceof HTMLImageElement) event.preventDefault();
    };

    document.addEventListener('contextmenu', onContextMenu);
    return () => document.removeEventListener('contextmenu', onContextMenu);
  }, []);

  return null;
}
